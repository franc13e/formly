"""Finds an Openverse photo for each curated recipe and writes src/data/recipePhotos.ts.

Curated photos are stored in the app so they load instantly and don't depend on
Openverse's anonymous rate limits at runtime. Re-run after adding curated recipes:

    python scripts/fetch_recipe_photos.py
"""

import asyncio
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import main  # noqa: E402  (reuses the backend's query chain and result mapping)


async def find(query: str):
    for q in main.openverse_queries(query):
        for attempt in range(3):
            try:
                photo = main._photo_from_openverse(await main.openverse_search(q))
                break
            except Exception as e:  # slow or throttled: back off and retry
                print(f"  retry {q!r} ({type(e).__name__})")
                await asyncio.sleep(3 * (attempt + 1))
        else:
            photo = None
        if photo:
            return photo
    return None


async def run():
    src = open(os.path.join(ROOT, "src/data/recipes.ts"), encoding="utf8").read()
    pairs = re.findall(r'id:\s*"([^"]+)",\s*name:\s*"[^"]*",\s*photoQuery:\s*"([^"]+)"', src)
    photos = {}
    for rid, query in pairs:
        photo = await find(query)
        print(f"{rid}: {'ok' if photo else 'none'}")
        if photo:
            photos[rid] = photo
        await asyncio.sleep(1.5)  # stay well under the anonymous burst limit
    body = json.dumps(photos, indent=2, ensure_ascii=False)
    out = (
        "// Generated by scripts/fetch_recipe_photos.py. Do not edit by hand.\n"
        "import type { RecipePhoto } from \"../types\";\n\n"
        "/** Openverse photos for the curated recipes, keyed by recipe id. */\n"
        f"export const CURATED_PHOTOS: Partial<Record<string, RecipePhoto>> = {body};\n"
    )
    open(os.path.join(ROOT, "src/data/recipePhotos.ts"), "w", encoding="utf8", newline="\n").write(out)
    print(f"wrote {len(photos)}/{len(pairs)} photos")


asyncio.run(run())
